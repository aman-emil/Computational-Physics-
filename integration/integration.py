import math

"""
Numerical Integration Routines
I implemented various quadrature and numerical integration methods here:
- Newton-Cotes methods: Midpoint rule, Trapezoidal rule, and Simpson's 1/3 rule.
- Monte Carlo integration: stochastic estimation of integrals and statistical variance.
- Gaussian Quadrature: Gauss-Legendre (finite intervals) and Gauss-Laguerre (semi-infinite intervals).
"""

def Mid_Pnt(func, interval, N):
    """
    Compute definite integral of func over interval [a, b] using the Midpoint rule with N intervals.
    I divide the interval into N subintervals of width h, evaluate func at each midpoint,
    and sum the resulting rectangular areas.
    """
    h = (interval[-1] - interval[0]) / N
    a = interval[0]
    x_array = [(a + n * h) for n in range(0, N + 1)]
    x_lead = x_array[:-1]
    x_lag = x_array[1:]
    x_mid_pnt_arr = [0] * N

    for idx in range(0, N):
        x_mid_pnt_arr[idx] = (x_lag[idx] + x_lead[idx]) / 2.0

    int_sum = 0
    for x in x_mid_pnt_arr:
        int_sum += func(x) * h

    return int_sum


def Trpz(func, interval, N):
    """
    Compute definite integral of func over interval [a, b] using the composite Trapezoidal rule with N intervals.
    I approximate the area under the curve by summing trapezoids formed between adjacent grid points.
    """
    h = (interval[-1] - interval[0]) / N
    a = interval[0]
    x_array = [(a + n * h) for n in range(0, N + 1)]

    int_sum = 0
    for n in range(N):
        x_n = x_array[n]
        x_n1 = x_array[n + 1]
        int_sum += (h / 2.0) * (func(x_n) + func(x_n1))

    return int_sum


def sim_s(func, a, b, N):
    """
    Compute definite integral using Simpson's 1/3 rule across [a, b] with N subintervals.
    I enforce that N must be even so pairs of intervals can be fitted with parabolas.
    Formula: (h / 3) * [f(x_0) + 4 * sum(f_odd) + 2 * sum(f_even) + f(x_n)]
    """
    if N % 2 != 0:
        print("Array must be even")
        return 0

    h = (b - a) / N
    interval = [a + i * h for i in range(N + 1)]
    func_val = [func(x) for x in interval]

    f_0 = func_val[0]
    f_n = func_val[-1]

    f_odd = func_val[1:-1:2]   # Indices 1, 3, 5, ...
    f_even = func_val[2:-1:2]  # Indices 2, 4, 6, ...

    Integral = (h / 3.0) * (f_0 + 4 * sum(f_odd) + 2 * sum(f_even) + f_n)
    return Integral


def ab_rand(a, b, lcg_step_func):
    """
    Helper function to scale a random number from [0, 1) generated by lcg_step_func into [a, b).
    I use this primarily to sample random points for Monte Carlo integration.
    """
    return a + (b - a) * lcg_step_func()


def Monte_Carlo_int(func, a, b, N, lcg_step_func):
    """
    Estimate definite integral and variance using the Monte Carlo method with N random samples.
    I draw random points in [a, b] using my custom LCG generator, evaluate func,
    estimate the integral as (b - a) * mean(f), and calculate the variance sigma^2.
    """
    i = 0
    integral_sum = 0.0
    sig_f_s = 0.0   # sum of f(x_i)
    sig_f_s1 = 0.0  # sum of f(x_i)^2

    while i < N:
        x_i = ab_rand(a, b, lcg_step_func)
        fx = func(x_i)

        integral_sum += fx
        sig_f_s += fx
        sig_f_s1 += fx**2
        i += 1

    Integral = (b - a) * (integral_sum / N)

    # Variance: sigma^2 = mean(f^2) - (mean(f))^2
    mean_f_sq = sig_f_s1 / N
    mean_f_mean_sq = (sig_f_s / N) ** 2
    sig_f_sq = mean_f_sq - mean_f_mean_sq

    return Integral, sig_f_sq


def Gauss_Quad(func, a, b, N):
    """
    Compute definite integral using Gaussian Quadrature up to order N (N in 1..5).
    - If upper limit b != "infty": I map [a, b] to [-1, 1] and perform Gauss-Legendre quadrature.
    - If upper limit b == "infty": I perform Gauss-Laguerre quadrature for integrals of the form
      int_0^inf f(x) dx = int_0^inf e^(-x) * [f(x) * e^x] dx.
    """
    # Gauss-Legendre quadrature roots on [-1, 1]
    lgroot = [
        [0.0000],                                                 # n = 1
        [-0.577350269, 0.577350269],                              # n = 2
        [-0.774596669, 0.0, 0.774596669],                         # n = 3
        [-0.861136312, -0.339981044, 0.339981044, 0.861136312],       # n = 4
        [-0.906179846, -0.538469310, 0.0, 0.538469310, 0.906179846] # n = 5
    ]

    # Gauss-Legendre weights
    lgweight = [
        [2.0000],                                                 # n = 1
        [1.0, 1.0],                                               # n = 2
        [0.5556, 0.8889, 0.5556],                                 # n = 3
        [0.3478, 0.6521, 0.6521, 0.3478],                         # n = 4
        [0.2369, 0.4786, 0.5689, 0.4786, 0.2369]                  # n = 5
    ]

    # Gauss-Laguerre roots on [0, infinity)
    lagroot = [
        [1.000],                                                    # n = 1
        [0.585786438, 3.414213562],                                 # n = 2
        [0.415774456, 2.294280360, 6.289945082],                    # n = 3
        [0.322547689, 1.745761101, 4.536620297, 9.395070912],        # n = 4
        [0.263560319718, 1.413403059107, 3.596425771041, 7.085810005859, 12.640800844276] # n = 5
    ]

    # Gauss-Laguerre weights
    lagweight = [
        [1.000],                                                    # n = 1
        [0.8535, 0.1464],                                           # n = 2
        [0.7111, 0.2785, 0.0104],                                   # n = 3
        [0.6032, 0.3574, 0.0389, 0.0005],                            # n = 4
        [0.521755610583, 0.398666811083, 0.075942449682, 0.003611758680, 0.000023369972] # n = 5
    ]

    func_root = []
    integral_val = 0

    if b != "infty":
        # Gauss-Legendre: coordinate transformation from [-1, 1] to [a, b]
        for r_val in lgroot[N - 1]:
            inp_1 = ((b - a) / 2.0) * r_val
            inp_2 = ((b + a) / 2.0)
            inp_f = inp_1 + inp_2
            func_val = func(inp_f)
            func_root.append(func_val)

        for wht, f_r in zip(lgweight[N - 1], func_root):
            integral_val += wht * f_r
        integral_val = ((b - a) / 2.0) * integral_val

    else:
        # Gauss-Laguerre: factor out the weighting function e^(-x)
        for r_val in lagroot[N - 1]:
            f_val = func(r_val) / math.exp(-r_val)
            func_root.append(f_val)

        for wht, f_r in zip(lagweight[N - 1], func_root):
            integral_val += wht * f_r

    return integral_val
